    def record_event(
        self, db: Session, user_id: str, session_id: str, *, kind: str, text_: str,
        after_version: Optional[int] = None, speak: bool = False, priority: str = "normal",
        proposal_id: Optional[str] = None, ttl_seconds: int = COACHING_TTL_SECONDS,
    ) -> Dict[str, Any]:
        eid = str(uuid.uuid4())
        expires = datetime.now(timezone.utc) + timedelta(seconds=ttl_seconds)
        db.execute(text("""
            INSERT INTO workout_session_event (
                id, session_id, user_id, after_version, kind, text, speak, priority,
                proposal_id, expires_at
            ) VALUES (
                :id, :sid, :uid, :ver, :kind, :text, :speak, :prio, :pid, :exp
            )
        """), {
            "id": eid, "sid": session_id, "uid": user_id, "ver": after_version,
            "kind": kind, "text": text_, "speak": speak, "prio": priority,
            "pid": proposal_id, "exp": expires,
        })
        return {
            "event_id": eid, "session_id": session_id, "after_version": after_version,
            "kind": kind, "text": text_, "speak": speak, "priority": priority,
            "expires_at": _iso(expires), "proposal_id": proposal_id,
        }

    def list_events(
        self, db: Session, session_id: str, *, after_version: Optional[int] = None, limit: int = 20
    ) -> List[Dict[str, Any]]:
        """Unexpired events for a session, oldest first.

        Expired rows are filtered rather than deleted — dropping stale coaching
        is a delivery decision (§6.7 step 6), and the history stays auditable.
        """
        sql = """
            SELECT id, after_version, kind, text, speak, priority, proposal_id, created_at, expires_at
            FROM workout_session_event
            WHERE session_id = :sid AND (expires_at IS NULL OR expires_at > NOW())
        """
        params: Dict[str, Any] = {"sid": session_id, "lim": limit}
        if after_version is not None:
            sql += " AND after_version > :ver"
            params["ver"] = after_version
        sql += " ORDER BY created_at ASC LIMIT :lim"
        rows = db.execute(text(sql), params).fetchall()
        return [{
            "event_id": r.id, "session_id": session_id, "after_version": r.after_version,
            "kind": r.kind, "text": r.text, "speak": r.speak, "priority": r.priority,
            "proposal_id": r.proposal_id, "expires_at": _iso(r.expires_at),
        } for r in rows]

    def _schedule_coaching(self, user_id: str, session_id: str, logged: Dict[str, Any]) -> None:
        """Kick off coaching generation without blocking the acknowledgement.

        Detached on purpose: the caller has already committed and returned, so
        an LLM timeout here costs a sentence, not a set.
        """
        try:
            asyncio.get_running_loop().create_task(
                self._generate_coaching(user_id, session_id, logged)
            )
        except RuntimeError:
            logger.debug("[WorkoutCommand] no running loop; skipping async coaching")

    async def _generate_coaching(self, user_id: str, session_id: str, logged: Dict[str, Any]) -> None:
        from app.db.session import SessionLocal
        from app.services.workout_session_service import workout_session_service as legacy

        db = SessionLocal()
        try:
            session = self._load_by_id(db, session_id)
            if not session or session["status"] != "active":
                return
            exercises = session["workout_snapshot"].get("exercises") or []
            entry = logged.get("logged") or {}
            ex_idx = entry.get("exercise_index") or 0
            ex = exercises[ex_idx] if 0 <= ex_idx < len(exercises) else {}
            nxt_idx = logged.get("next_exercise_index")
            feedback = await legacy._generate_set_feedback(
                exercise_name=entry.get("exercise") or "",
                set_number=entry.get("set_number") or 1,
                total_sets=ex.get("sets") or 0,
                weight=entry.get("weight") or 0,
                reps=entry.get("reps") or 0,
                rpe=entry.get("rpe"),
                suggested_weight=ex.get("approved_weight") or ex.get("suggested_weight"),
                is_last_set=bool(logged.get("exercise_complete")),
                workout_complete=bool(logged.get("workout_complete")),
                next_exercise=exercises[nxt_idx] if isinstance(nxt_idx, int) and nxt_idx < len(exercises) else None,
                rest_seconds=logged.get("rest_seconds") or 0,
            )
            policy = self.get_policy(db, user_id)
            proposal = logged.get("proposal")
            self.record_event(
                db, user_id, session_id,
                kind="set_feedback",
                text_=feedback.get("text") or "",
                after_version=session["version"],
                speak=bool(policy.get("speak_routine_coaching")),
            )
            if logged.get("pr") and policy.get("speak_prs"):
                self.record_event(
                    db, user_id, session_id, kind="pr",
                    text_=f"New personal record on {entry.get('exercise')}.",
                    after_version=session["version"], speak=True, priority="high",
                )
            if proposal:
                self.record_event(
                    db, user_id, session_id, kind="proposal",
                    text_=proposal.get("reason") or "I have a recommendation.",
                    after_version=session["version"],
                    speak=bool(policy.get("speak_proposals")),
                    priority="high", proposal_id=proposal.get("proposal_id"),
                    ttl_seconds=PROPOSAL_TTL_SECONDS,
                )
            db.commit()
        except Exception as e:
            db.rollback()
            logger.warning(f"[WorkoutCommand] coaching generation failed (non-fatal): {e}")
        finally:
            db.close()

