    async def _apply_complete(
        self, db: Session, session: Dict[str, Any], payload: Dict[str, Any]
    ) -> Dict[str, Any]:
        from app.services.workout_session_service import workout_session_service as legacy

        now = datetime.now(timezone.utc)
        started = session.get("started_at")
        duration_minutes = int((now - started).total_seconds() / 60) if started else 0

        hk_uuid = payload.get("healthkit_workout_uuid")
        db.execute(text("""
            UPDATE active_workout_session
            SET status = 'completed', completed_at = NOW(), updated_at = NOW(),
                version = version + 1,
                healthkit_state = COALESCE(:hk_state, healthkit_state),
                healthkit_workout_uuid = COALESCE(:hk_uuid, healthkit_workout_uuid),
                healthkit_ended_at = COALESCE(:hk_ended, healthkit_ended_at)
            WHERE id = :sid
        """), {
            "sid": session["id"],
            "hk_state": "ended" if hk_uuid else None,
            "hk_uuid": hk_uuid,
            "hk_ended": payload.get("healthkit_ended_at"),
        })
        if hk_uuid:
            db.execute(text("""
                UPDATE external_workout SET sara_session_id = :sid
                WHERE user_id = :uid AND external_id = :hk
            """), {"sid": session["id"], "uid": session["user_id"], "hk": hk_uuid})

        # Post-workout progression is a proposal for *next* time, approved out
        # of the gym rather than at the next start (§6.8).
        self._create_next_session_proposals(db, session)

        heart_rate = self._linked_heart_rate(db, session, hk_uuid) or legacy._meld_external_workout(
            db, session["user_id"], started, now
        )

        return {
            "summary": {
                "workout_name": session["workout_snapshot"].get("template_name", "Workout"),
                "duration_minutes": duration_minutes,
                "total_sets": session["total_sets_completed"],
                "total_volume": session["total_volume"],
                "exercises_completed": session["current_exercise_index"],
                "heart_rate": heart_rate,
            },
            "completed_at": now.isoformat(),
        }

    async def _apply_abandon(
        self, db: Session, session: Dict[str, Any], *, delete_sets: bool
    ) -> Dict[str, Any]:
        if delete_sets:
            # An abandoned workout leaves no trace in history — this preserves
            # the existing product rule (§4.6).
            db.execute(text("DELETE FROM workout_log WHERE active_session_id = :sid"), {"sid": session["id"]})
            db.execute(text("DELETE FROM workout WHERE id = :sid"), {"sid": session["id"]})
        db.execute(text("""
            UPDATE active_workout_session
            SET status = 'abandoned', completed_at = NOW(), updated_at = NOW(), version = version + 1
            WHERE id = :sid
        """), {"sid": session["id"]})
        db.execute(text("""
            UPDATE workout_adjustment_proposal
            SET status = 'superseded', resolved_at = NOW()
            WHERE session_id = :sid AND status = 'pending'
        """), {"sid": session["id"]})
        return {"abandoned": True}

