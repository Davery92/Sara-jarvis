    def _create_proposal(
        self, db: Session, user_id: str, session_id: Optional[str], *,
        kind: str, scope: Dict[str, Any], current_value: Dict[str, Any],
        proposed_value: Dict[str, Any], reason: str, evidence: Optional[Dict[str, Any]] = None,
        ttl_seconds: Optional[int] = PROPOSAL_TTL_SECONDS,
    ) -> Dict[str, Any]:
        # One live proposal per scope — a newer recommendation supersedes the
        # old one rather than queueing two answers to the same question.
        db.execute(text("""
            UPDATE workout_adjustment_proposal
            SET status = 'superseded', resolved_at = NOW()
            WHERE user_id = :uid AND status = 'pending' AND kind = :kind
              AND scope = CAST(:scope AS jsonb)
              AND (session_id = :sid OR (session_id IS NULL AND :sid IS NULL))
        """), {"uid": user_id, "kind": kind, "scope": json.dumps(scope), "sid": session_id})

        pid = str(uuid.uuid4())
        expires = (
            datetime.now(timezone.utc) + timedelta(seconds=ttl_seconds) if ttl_seconds else None
        )
        db.execute(text("""
            INSERT INTO workout_adjustment_proposal (
                id, user_id, session_id, kind, scope, current_value, proposed_value,
                reason, evidence, status, expires_at
            ) VALUES (
                :id, :uid, :sid, :kind, CAST(:scope AS jsonb), CAST(:cur AS jsonb),
                CAST(:prop AS jsonb), :reason, CAST(:ev AS jsonb), 'pending', :exp
            )
        """), {
            "id": pid, "uid": user_id, "sid": session_id, "kind": kind,
            "scope": json.dumps(scope), "cur": json.dumps(current_value),
            "prop": json.dumps(proposed_value), "reason": reason,
            "ev": json.dumps(evidence or {}, default=str), "exp": expires,
        })
        return {
            "proposal_id": pid, "session_id": session_id, "kind": kind, "scope": scope,
            "current_value": current_value, "proposed_value": proposed_value,
            "reason": reason, "evidence": evidence or {}, "status": "pending",
            "expires_at": _iso(expires),
        }

    def _maybe_propose_weight(
        self, db: Session, session: Dict[str, Any], exercises: List[Dict[str, Any]],
        ex_idx: int, rpe: int, reps: int, logged_weight: float,
    ) -> Optional[Dict[str, Any]]:
        if ex_idx >= len(exercises):
            return None
        ex = exercises[ex_idx]
        # A first-ever exercise has no prescription yet; the weight David just
        # chose is the target the recommendation is measured against.
        approved = ex.get("approved_weight") or ex.get("suggested_weight") or logged_weight
        if not approved:
            return None
        target_rpe = ex.get("rpe_target") or 8
        delta = 0
        if rpe >= int(target_rpe) + 1:
            delta = -5
        elif rpe <= int(target_rpe) - 2:
            delta = 5
        if not delta:
            return None
        return self._create_proposal(
            db, session["user_id"], session["id"],
            kind="next_set_weight",
            scope={"exercise_index": ex_idx},
            current_value={"weight": float(approved)},
            proposed_value={"weight": float(approved) + delta},
            reason=(
                "The last set was above the approved effort target."
                if delta < 0 else
                "The last set came in well under the approved effort target."
            ),
            evidence={"target_rpe": target_rpe, "reported_rpe": rpe, "completed_reps": reps},
        )

    def _approved_next_session_weights(self, db: Session, user_id: str) -> Dict[str, float]:
        """Progressions David approved out of the gym, by exercise name (§6.8).

        Newest wins if he answered the same question twice.
        """
        try:
            rows = db.execute(text("""
                SELECT scope, proposed_value FROM workout_adjustment_proposal
                WHERE user_id = :uid AND kind = 'next_session_weight' AND status = 'approved'
                ORDER BY resolved_at ASC
            """), {"uid": user_id}).fetchall()
        except Exception:
            return {}

        approved: Dict[str, float] = {}
        for r in rows:
            scope = r.scope if isinstance(r.scope, dict) else json.loads(r.scope or "{}")
            value = r.proposed_value if isinstance(r.proposed_value, dict) else json.loads(r.proposed_value or "{}")
            name, weight = scope.get("exercise"), value.get("weight")
            if name and weight is not None:
                approved[name] = float(weight)
        return approved

    def _create_next_session_proposals(self, db: Session, session: Dict[str, Any]) -> None:
        """After the workout, propose next time's weights — never apply them."""
        if not _v2_enabled():
            return
        from app.services.workout_session_service import workout_session_service as legacy
        snap = session["workout_snapshot"]
        is_deload = bool(snap.get("is_deload"))
        for ex in (snap.get("exercises") or []):
            name = legacy._effective_name(ex)
            if not name:
                continue
            try:
                suggestion = legacy._compute_suggestion(
                    session["user_id"], name, ex.get("reps", "8-10"), is_deload, db
                )
            except Exception as e:
                logger.warning(f"[WorkoutCommand] next-session suggestion failed for {name}: {e}")
                continue
            calc = suggestion.get("suggested_weight")
            approved = ex.get("approved_weight") or ex.get("suggested_weight")
            if calc is None or approved is None or float(calc) == float(approved):
                continue
            self._create_proposal(
                db, session["user_id"], None,
                kind="next_session_weight",
                scope={"exercise": name},
                current_value={"weight": float(approved)},
                proposed_value={"weight": float(calc)},
                reason=suggestion.get("progression_note") or f"Progression for {name}.",
                evidence={"last_session": suggestion.get("last_session")},
                ttl_seconds=None,
            )

    def _apply_resolve_proposal(
        self, db: Session, session: Optional[Dict[str, Any]], user_id: str,
        payload: Dict[str, Any], origin: str, command_id: str, *, approve: bool,
    ) -> Dict[str, Any]:
        pid = payload.get("proposal_id")
        if not pid:
            raise ValueError("proposal_id is required")

        row = db.execute(text("""
            SELECT id, session_id, kind, scope, current_value, proposed_value, status, expires_at
            FROM workout_adjustment_proposal
            WHERE id = :id AND user_id = :uid FOR UPDATE
        """), {"id": pid, "uid": user_id}).fetchone()
        if not row:
            raise WorkoutConflict("proposal_stale", "That recommendation no longer exists.")
        if row.status != "pending":
            return {"proposal": {"proposal_id": pid, "status": row.status}, "applied": False}
        if row.expires_at and row.expires_at < datetime.now(timezone.utc):
            db.execute(text(
                "UPDATE workout_adjustment_proposal SET status='expired', resolved_at=NOW() WHERE id=:id"
            ), {"id": pid})
            raise WorkoutConflict("proposal_stale", "That recommendation expired.")

        if not approve:
            # Rejection changes nothing but the ledger (§11.3).
            db.execute(text("""
                UPDATE workout_adjustment_proposal
                SET status='rejected', resolved_at=NOW(), resolved_by_device=:dev, approval_command_id=:cid
                WHERE id = :id
            """), {"id": pid, "dev": origin, "cid": command_id})
            return {"proposal": {"proposal_id": pid, "status": "rejected"}, "applied": False}

        applied = self._apply_proposed_value(db, session, row)

        db.execute(text("""
            UPDATE workout_adjustment_proposal
            SET status='approved', resolved_at=NOW(), resolved_by_device=:dev, approval_command_id=:cid
            WHERE id = :id
        """), {"id": pid, "dev": origin, "cid": command_id})
        return {"proposal": {"proposal_id": pid, "status": "approved"}, "applied": applied}

    def _apply_proposed_value(self, db: Session, session: Optional[Dict[str, Any]], row) -> bool:
        """Write exactly the proposed value, nothing adjacent to it (§11.3)."""
        scope = row.scope if isinstance(row.scope, dict) else json.loads(row.scope or "{}")
        proposed = row.proposed_value if isinstance(row.proposed_value, dict) else json.loads(row.proposed_value or "{}")

        if row.kind in ("next_set_weight", "exercise_weight"):
            if session is None:
                # Scoped to a live workout by exercise index; with no session
                # that index means nothing. Refuse rather than guess.
                raise WorkoutConflict(
                    "proposal_stale", "That workout is no longer running."
                )
            snap = session["workout_snapshot"]
            exercises = snap.get("exercises") or []
            idx = scope.get("exercise_index")
            if idx is None or idx < 0 or idx >= len(exercises):
                raise WorkoutConflict("proposal_stale", "That exercise is no longer in this workout.")
            weight = proposed.get("weight")
            if weight is None:
                return False
            exercises[idx]["approved_weight"] = weight
            exercises[idx]["suggested_weight"] = weight
            db.execute(text("""
                UPDATE active_workout_session SET workout_snapshot = CAST(:snap AS jsonb) WHERE id = :sid
            """), {"snap": json.dumps(snap), "sid": session["id"]})
            return True

        if row.kind == "next_session_weight":
            # Nothing to mutate in *this* session — the approval is the record,
            # and `_approved_next_session_weights` turns it into the next
            # workout's prescription (then retires it).
            return True

        logger.warning(f"[WorkoutCommand] no applicator for proposal kind {row.kind}")
        return False

    def _pending_proposal(self, db: Session, user_id: str, session_id: str) -> Optional[Dict[str, Any]]:
        try:
            row = db.execute(text("""
                SELECT id, kind, scope, current_value, proposed_value, reason, evidence, expires_at
                FROM workout_adjustment_proposal
                WHERE user_id = :uid AND session_id = :sid AND status = 'pending'
                  AND (expires_at IS NULL OR expires_at > NOW())
                ORDER BY created_at DESC LIMIT 1
            """), {"uid": user_id, "sid": session_id}).fetchone()
        except Exception:
            return None
        if not row:
            return None
        return {
            "proposal_id": row.id, "session_id": session_id, "kind": row.kind,
            "scope": row.scope, "current_value": row.current_value,
            "proposed_value": row.proposed_value, "reason": row.reason,
            "evidence": row.evidence, "status": "pending", "expires_at": _iso(row.expires_at),
        }

