def _last_approved_weight(last_session: Optional[Dict[str, Any]]) -> Optional[float]:
    """The heaviest weight actually lifted last time for this exercise.

    That is the most recent prescription David *executed*, so it is what an
    unapproved progression is measured against.
    """
    if not last_session:
        return None
    weights = [w for w in (last_session.get("weights") or []) if w]
    if not weights:
        return None
    try:
        return float(max(weights))
    except (TypeError, ValueError):
        return None


