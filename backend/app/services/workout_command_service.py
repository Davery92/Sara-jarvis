    def _apply_set_variant(self, db: Session, session: Dict[str, Any], payload: Dict[str, Any]) -> Dict[str, Any]:
        from app.services.workout_session_service import workout_session_service as legacy
        snap = session["workout_snapshot"]
        exercises = snap.get("exercises") or []
        idx = int(payload.get("exercise_index", -1))
        if idx < 0 or idx >= len(exercises):
            raise ValueError(f"Exercise index {idx} out of range")

        ex = exercises[idx]
        clean = (payload.get("variant") or "").strip()
        ex["variant"] = None if (not clean or clean.lower() == (ex.get("name") or "").lower()) else clean

        # Re-scope the prescription to the machine actually being used, so hack
        # squat weights never land on the barbell squat's history.
        effective = legacy._effective_name(ex)
        suggestion = legacy._compute_suggestion(
            session["user_id"], effective, ex.get("reps", "8-10"), bool(snap.get("is_deload")), db
        )
        calculated = suggestion["suggested_weight"]
        approved = calculated
        if _v2_enabled():
            approved = _last_approved_weight(suggestion.get("last_session")) or calculated
        ex["suggested_weight"] = approved
        ex["approved_weight"] = approved
        ex["calculated_suggestion"] = calculated
        ex["progression_note"] = suggestion["progression_note"]
        ex["last_session"] = suggestion["last_session"]

        db.execute(text("""
            UPDATE active_workout_session SET workout_snapshot = CAST(:snap AS jsonb) WHERE id = :sid
        """), {"snap": json.dumps(snap), "sid": session["id"]})

        if idx == session["current_exercise_index"]:
            counts = self._name_counts(db, session["id"])
            db.execute(text("""
                UPDATE active_workout_session SET current_set_index = :si WHERE id = :sid
            """), {"si": legacy._completed_for(exercises, counts, idx), "sid": session["id"]})

        return {
            "exercise_index": idx, "variant": ex["variant"], "effective_name": effective,
            "approved_weight": approved, "calculated_suggestion": calculated,
            "last_session": ex["last_session"],
        }

    def _apply_skip(self, db: Session, session: Dict[str, Any]) -> Dict[str, Any]:
        from app.services.workout_session_service import workout_session_service as legacy
        exercises = session["workout_snapshot"].get("exercises") or []
        cur = session["current_exercise_index"]
        if not exercises:
            return {"skipped_exercise": None, "next_exercise": None, "workout_complete": True}

        counts = self._name_counts(db, session["id"])
        # A skipped exercise stays incomplete on purpose — the machine may free
        # up later, and _next_incomplete_index wraps back around to it.
        nxt = legacy._next_incomplete_index(exercises, counts, cur)
        new_idx = cur if nxt is None else nxt
        db.execute(text("""
            UPDATE active_workout_session
            SET current_exercise_index = :ei, current_set_index = :si WHERE id = :sid
        """), {
            "ei": new_idx,
            "si": legacy._completed_for(exercises, counts, new_idx),
            "sid": session["id"],
        })
        return {
            "skipped_exercise": exercises[cur]["name"] if cur < len(exercises) else None,
            "next_exercise": exercises[nxt]["name"] if nxt is not None else None,
            "workout_complete": nxt is None,
        }

