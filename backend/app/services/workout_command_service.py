class WorkoutConflict(Exception):
    """A command could not be applied against the current state.

    `code` is the machine-readable reason the client branches on:
      active_workout_conflict / version_conflict / session_mismatch /
      no_active_session / proposal_stale
    """

    def __init__(self, code: str, message: str, projection: Optional[Dict[str, Any]] = None):
        super().__init__(message)
        self.code = code
        self.message = message
        self.projection = projection


class WorkoutCommandService:
    # ────────────────────────────────────────────────────────────────────
    # Session loading / projection
    # ────────────────────────────────────────────────────────────────────

    def _lock_active_row(self, db: Session, user_id: str) -> Optional[Dict[str, Any]]:
        """Fetch the user's active session with a row lock held for the txn.

        FOR UPDATE is what serialises two devices racing the same mutation:
        the second one blocks until the first has bumped `version`, and then
        fails its expected_version check instead of overwriting.
        """
        row = db.execute(text("""
            SELECT id, user_id, template_id, status, started_at, completed_at,
                   current_exercise_index, current_set_index, workout_snapshot,
                   rest_timer_started_at, rest_timer_duration_seconds,
                   total_sets_completed, total_volume, notes, updated_at,
                   version, origin_device, start_attempt_id,
                   healthkit_state, healthkit_workout_uuid, healthkit_activity_type,
                   healthkit_started_at, healthkit_ended_at, last_device_sync_at
            FROM active_workout_session
            WHERE user_id = :uid AND status = 'active'
            FOR UPDATE
        """), {"uid": user_id}).fetchone()
        return self._hydrate(row) if row else None

    def _load_by_id(self, db: Session, session_id: str) -> Optional[Dict[str, Any]]:
        row = db.execute(text("""
            SELECT id, user_id, template_id, status, started_at, completed_at,
                   current_exercise_index, current_set_index, workout_snapshot,
                   rest_timer_started_at, rest_timer_duration_seconds,
                   total_sets_completed, total_volume, notes, updated_at,
                   version, origin_device, start_attempt_id,
                   healthkit_state, healthkit_workout_uuid, healthkit_activity_type,
                   healthkit_started_at, healthkit_ended_at, last_device_sync_at
            FROM active_workout_session WHERE id = :sid
        """), {"sid": session_id}).fetchone()
        return self._hydrate(row) if row else None

    @staticmethod
    def _hydrate(row) -> Dict[str, Any]:
        s = dict(row._mapping)
        snap = s.get("workout_snapshot")
        if isinstance(snap, str):
            s["workout_snapshot"] = json.loads(snap) if snap else {}
        elif snap is None:
            s["workout_snapshot"] = {}
        s["total_volume"] = float(s["total_volume"]) if s.get("total_volume") else 0.0
        s["version"] = int(s.get("version") or 1)
        return s

    def _name_counts(self, db: Session, session_id: str) -> Dict[str, int]:
        rows = db.execute(text("""
            SELECT exercise_id, COUNT(*) AS c FROM workout_log
            WHERE active_session_id = :sid GROUP BY exercise_id
        """), {"sid": session_id}).fetchall()
        return {r.exercise_id: int(r.c) for r in rows}

    def projection(
        self, db: Session, session: Optional[Dict[str, Any]], *, compact: bool = False
    ) -> Optional[Dict[str, Any]]:
        """The complete renderable state both devices agree on (§5.1).

        Everything a controller needs to draw a screen is in here, so a device
        that has been offline can catch up from one payload instead of
        replaying a change log.
        """
        if not session:
            return None

        from app.services.workout_session_service import workout_session_service as legacy

        snap = session.get("workout_snapshot") or {}
        exercises: List[Dict[str, Any]] = snap.get("exercises") or []
        counts = self._name_counts(db, session["id"])

        for ex in exercises:
            target = ex.get("sets", 0) or 0
            ex["completed_sets"] = min(counts.get(legacy._effective_name(ex), 0), target)
            # Older sessions predate the approved/calculated split — treat the
            # value they were started with as already approved.
            ex.setdefault("approved_weight", ex.get("suggested_weight"))
            ex.setdefault("calculated_suggestion", ex.get("suggested_weight"))

        cur_idx = session.get("current_exercise_index") or 0
        cur = exercises[cur_idx] if 0 <= cur_idx < len(exercises) else None

        rest_started = session.get("rest_timer_started_at")
        rest_duration = session.get("rest_timer_duration_seconds")
        rest_active = False
        if rest_started and rest_duration:
            elapsed = (datetime.now(timezone.utc) - rest_started).total_seconds()
            rest_active = elapsed < rest_duration

        proj: Dict[str, Any] = {
            "schema_version": SCHEMA_VERSION,
            "session_id": session["id"],
            "version": session["version"],
            "status": session["status"],
            "started_at": _iso(session.get("started_at")),
            "origin_device": session.get("origin_device"),
            "template": {
                "id": session.get("template_id"),
                "name": snap.get("template_name") or "Workout",
                "is_deload": bool(snap.get("is_deload")),
            },
            "cursor": {
                "exercise_index": cur_idx,
                "set_index": session.get("current_set_index") or 0,
            },
            "progress": {
                "completed_sets": session.get("total_sets_completed") or 0,
                "total_sets": snap.get("total_sets") or sum((e.get("sets") or 0) for e in exercises),
                "total_volume": session.get("total_volume") or 0.0,
            },
            "current_exercise": _exercise_view(cur) if cur else None,
            "rest": {
                "active": rest_active,
                "started_at": _iso(rest_started),
                "duration_seconds": rest_duration,
            },
            "healthkit": {
                "state": session.get("healthkit_state"),
                "workout_uuid": session.get("healthkit_workout_uuid"),
                "activity_type": session.get("healthkit_activity_type"),
                "started_at": _iso(session.get("healthkit_started_at")),
                "ended_at": _iso(session.get("healthkit_ended_at")),
            },
            "pending_proposal": self._pending_proposal(db, session["user_id"], session["id"]),
            "updated_at": _iso(session.get("updated_at")),
        }
        if not compact:
            # The Watch renders from `current_exercise` alone; the phone needs
            # the whole list for the exercise picker and jump-in-any-order.
            proj["exercises"] = [_exercise_view(e) for e in exercises]
        return proj

    # ────────────────────────────────────────────────────────────────────
    # Start (§4.2, §4.3, §6.6)
    # ────────────────────────────────────────────────────────────────────

    async def start(
        self,
        db: Session,
        user_id: str,
        template_id: str,
        *,
        start_attempt_id: Optional[str] = None,
        origin_device: str = "phone",
        on_conflict: str = "error",
        healthkit_started_at: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Create (or replay, or refuse to clobber) the canonical session.

        `on_conflict="error"` is the §6.6 contract: an active workout for a
        different template is a 409 the user resolves, never a silent abandon.
        The legacy phone endpoint passes "abandon" while
        WORKOUT_COMMAND_V2_ENABLED is off so today's behaviour is unchanged
        until the phone has moved over.
        """
        try:
            # 1. Idempotent replay: the same start attempt returns the same
            #    session, so a Watch retrying through a dropped link cannot
            #    create a second workout.
            if start_attempt_id:
                existing = db.execute(text("""
                    SELECT id FROM active_workout_session
                    WHERE user_id = :uid AND start_attempt_id = :aid
                    ORDER BY started_at DESC LIMIT 1
                """), {"uid": user_id, "aid": start_attempt_id}).fetchone()
                if existing:
                    sess = self._load_by_id(db, existing.id)
                    return {"status": "replayed", "projection": self.projection(db, sess)}

            active = self._lock_active_row(db, user_id)
            if active:
                same_template = str(active.get("template_id") or "") == str(template_id)
                if same_template:
                    # Resume, don't restart — the sets already logged stand.
                    return {"status": "resumed", "projection": self.projection(db, active)}
                if on_conflict == "abandon":
                    await self._apply_abandon(db, active, delete_sets=True)
                else:
                    raise WorkoutConflict(
                        "active_workout_conflict",
                        "A different workout is already active. Resume it or end it first.",
                        self.projection(db, active),
                    )

            projection = await self._create_session(
                db, user_id, template_id,
                start_attempt_id=start_attempt_id,
                origin_device=origin_device,
                healthkit_started_at=healthkit_started_at,
            )
            db.commit()
            return {"status": "accepted", "projection": projection}

        except WorkoutConflict:
            db.rollback()
            raise
        except Exception:
            db.rollback()
            logger.exception("[WorkoutCommand] start failed")
            raise

    async def _create_session(
        self,
        db: Session,
        user_id: str,
        template_id: str,
        *,
        start_attempt_id: Optional[str],
        origin_device: str,
        healthkit_started_at: Optional[str],
    ) -> Dict[str, Any]:
        from app.services.progressive_overload import get_deload_state
        from app.services.workout_session_service import workout_session_service as legacy

        row = db.execute(text("""
            SELECT id, name, phase_id, scheduled_days, exercises, notes
            FROM fitness_template WHERE id = :tid AND user_id = :uid
        """), {"tid": template_id, "uid": user_id}).fetchone()
        if not row:
            raise ValueError(f"Template {template_id} not found")

        template = dict(row._mapping)
        raw = template.get("exercises") or "[]"
        specs = json.loads(raw) if isinstance(raw, str) else (raw or [])

        deload = get_deload_state(db=db, user_id=user_id, on_date=date.today())
        is_deload = deload["is_deload"]
        enforce_approval = _v2_enabled()
        consumed_approvals = self._approved_next_session_weights(db, user_id) if enforce_approval else {}

        snapshots = []
        for spec in specs:
            name = spec.get("name")
            target_sets = spec.get("sets", 3)
            target_reps = spec.get("reps", "8-10")
            suggestion = legacy._compute_suggestion(user_id, name, target_reps, is_deload, db)
            calculated = suggestion["suggested_weight"]

            # §6.8 — calculation is not application. The workout starts on the
            # weight David last actually approved; Sara's new number rides along
            # as a proposal she has to be told to apply. With the v2 flag off
            # this collapses to today's behaviour.
            approved = calculated
            if enforce_approval:
                # A progression he already approved out of the gym IS the
                # current prescription — otherwise approving it did nothing and
                # he'd be asked the same question again at the rack.
                approved = (
                    consumed_approvals.get(name)
                    or _last_approved_weight(suggestion.get("last_session"))
                    or calculated
                )

            effective_sets = target_sets
            if is_deload:
                try:
                    effective_sets = max(2, int(target_sets) // 2)
                except (TypeError, ValueError):
                    effective_sets = target_sets

            snapshots.append({
                "name": name,
                "variant": None,
                "sets": effective_sets,
                "sets_original": target_sets if is_deload else None,
                "reps": target_reps,
                "rpe_target": spec.get("rpe_target", 7),
                "rest_seconds": spec.get("rest_seconds", 120),
                "notes": spec.get("notes"),
                "metric_type": spec.get("metric_type", "reps"),
                "is_per_side": bool(spec.get("is_per_side", False)),
                "superset_group": spec.get("superset_group"),
                "set_technique": spec.get("set_technique"),
                # `suggested_weight` stays the field the existing phone UI
                # reads, and always holds the value to actually lift.
                "suggested_weight": approved,
                "approved_weight": approved,
                "calculated_suggestion": calculated,
                "progression_note": suggestion["progression_note"],
                "last_session": suggestion["last_session"],
            })

        snapshot = {
            "template_id": template_id,
            "template_name": template["name"],
            "template_notes": template.get("notes"),
            "exercises": snapshots,
            "total_sets": sum(e["sets"] for e in snapshots),
            "is_deload": is_deload,
            "week_of_phase": deload.get("week_of_phase"),
            "deload_week": deload.get("deload_week"),
            "phase_name": deload.get("phase_name"),
        }

        session_id = str(uuid.uuid4())
        db.execute(text("""
            INSERT INTO workout (id, user_id, title, status)
            VALUES (:id, :uid, :title, 'in_progress')
        """), {"id": session_id, "uid": user_id, "title": template["name"]})

        db.execute(text("""
            INSERT INTO active_workout_session (
                id, user_id, template_id, status, workout_snapshot,
                version, origin_device, start_attempt_id,
                healthkit_state, healthkit_started_at, last_device_sync_at
            ) VALUES (
                :id, :uid, :tid, 'active', CAST(:snap AS jsonb),
                1, :origin, :aid,
                :hk_state, :hk_started, NOW()
            )
        """), {
            "id": session_id, "uid": user_id, "tid": template_id,
            "snap": json.dumps(snapshot), "origin": origin_device,
            "aid": start_attempt_id,
            "hk_state": "running" if healthkit_started_at else None,
            "hk_started": healthkit_started_at,
        })

        session = self._load_by_id(db, session_id)

        # A carried-over approval applies to exactly this workout. Retiring it
        # here stops it silently re-applying to every future session, which
        # would turn one "yes" into standing permission.
        if consumed_approvals:
            db.execute(text("""
                UPDATE workout_adjustment_proposal
                SET status = 'superseded', resolved_at = NOW()
                WHERE user_id = :uid AND kind = 'next_session_weight' AND status = 'approved'
            """), {"uid": user_id})

        # Surface the held-back progression as an approvable proposal rather
        # than quietly lifting more than David agreed to.
        if enforce_approval:
            for idx, ex in enumerate(snapshots):
                calc, appr = ex.get("calculated_suggestion"), ex.get("approved_weight")
                if calc is not None and appr is not None and float(calc) != float(appr):
                    self._create_proposal(
                        db, user_id, session_id,
                        kind="exercise_weight",
                        scope={"exercise_index": idx},
                        current_value={"weight": appr},
                        proposed_value={"weight": calc},
                        reason=ex.get("progression_note") or "Progression from your last session.",
                        evidence={"last_session": ex.get("last_session")},
                        ttl_seconds=None,
                    )

        return self.projection(db, session)

    # ────────────────────────────────────────────────────────────────────
    # Command execution (§5.2, §6.2)
    # ────────────────────────────────────────────────────────────────────

    async def execute(self, db: Session, user_id: str, envelope: Dict[str, Any]) -> Dict[str, Any]:
        """Apply one command envelope exactly once."""
        command_id = envelope.get("command_id")
        kind = envelope.get("kind")
        if not command_id:
            raise ValueError("command_id is required")
        if kind not in MUTATING_KINDS:
            raise ValueError(f"unknown command kind: {kind!r}")

        payload = envelope.get("payload") or {}
        expected_version = envelope.get("expected_version")
        claimed_session = envelope.get("session_id")
        origin = envelope.get("origin_device") or "phone"

        try:
            # 2. Replay — return the stored result verbatim. Both devices then
            #    converge on the same answer no matter who retried.
            prior = db.execute(text("""
                SELECT result FROM workout_session_command
                WHERE command_id = :cid AND user_id = :uid
            """), {"cid": command_id, "uid": user_id}).fetchone()
            if prior:
                stored = prior.result or {}
                if isinstance(stored, str):
                    stored = json.loads(stored)
                return {**stored, "status": "replayed"}

            # 3. Lock.
            session = self._lock_active_row(db, user_id)

            # Two kinds are about consent rather than session state and must
            # work with no workout running: standing policy, and resolving a
            # proposal. Post-workout progression is deliberately approved out
            # of the gym (§6.8) — requiring an active session would make those
            # proposals unanswerable until David was back under a bar.
            if kind == "set_policy":
                result = self._apply_set_policy(db, user_id, payload, origin)
                self._record_command(db, command_id, None, user_id, origin, kind,
                                     expected_version, payload, result, "applied")
                db.commit()
                return result

            if not session and kind in ("approve_proposal", "reject_proposal"):
                result = self._apply_resolve_proposal(
                    db, None, user_id, payload, origin, command_id,
                    approve=(kind == "approve_proposal"),
                )
                result = {"status": "accepted", "command_id": command_id,
                          "projection": None, **result}
                self._record_command(db, command_id, None, user_id, origin, kind,
                                     expected_version, payload, result, "applied")
                db.commit()
                return result

            if not session:
                raise WorkoutConflict("no_active_session", "No active workout session.")

            # 4. Validate. A command minted against a workout that has since
            #    ended must not land on its replacement.
            if claimed_session and str(claimed_session) != str(session["id"]):
                raise WorkoutConflict(
                    "session_mismatch",
                    "That action was for a different workout.",
                    self.projection(db, session),
                )
            if expected_version is not None and int(expected_version) != session["version"]:
                raise WorkoutConflict(
                    "version_conflict",
                    "The workout changed on another device.",
                    self.projection(db, session),
                )

            # 5. Apply once.
            extra = await self._dispatch(db, session, kind, payload, origin, command_id)

            # 6. Bump version (skipped for the terminal kinds, which set their
            #    own status and are already reloaded by the handler).
            if kind not in ("complete", "abandon"):
                self._bump(db, session["id"], origin)

            fresh = self._load_by_id(db, session["id"])
            result = {
                "status": "accepted",
                "command_id": command_id,
                "projection": self.projection(db, fresh),
                **extra,
            }

            # 7. Store the result so a replay is free and exact.
            self._record_command(db, command_id, session["id"], user_id, origin, kind,
                                 expected_version, payload, result, "applied")
            db.commit()

            # Coaching happens strictly after the commit (§6.7): the set is
            # already durable, so a hung LLM cannot make Log Set look broken.
            if kind == "log_set":
                self._schedule_coaching(user_id, session["id"], extra)
            return result

        except WorkoutConflict as c:
            db.rollback()
            try:
                self._record_command(db, command_id, claimed_session, user_id, origin, kind,
                                     expected_version, payload,
                                     {"status": "conflict", "code": c.code, "message": c.message},
                                     "conflict")
                db.commit()
            except Exception:
                db.rollback()
            raise
        except Exception:
            db.rollback()
            logger.exception(f"[WorkoutCommand] {kind} failed")
            raise

    async def _dispatch(
        self, db: Session, session: Dict[str, Any], kind: str,
        payload: Dict[str, Any], origin: str, command_id: str,
    ) -> Dict[str, Any]:
        if kind == "log_set":
            return await self._apply_log_set(db, session, payload, command_id)
        if kind == "select_exercise":
            return self._apply_select_exercise(db, session, payload)
        if kind == "set_variant":
            return self._apply_set_variant(db, session, payload)
        if kind == "skip_exercise":
            return self._apply_skip(db, session)
        if kind == "rest_start":
            return self._apply_rest_start(db, session, payload)
        if kind == "rest_stop":
            return self._apply_rest_stop(db, session)
        if kind == "complete":
            return await self._apply_complete(db, session, payload)
        if kind == "abandon":
            return await self._apply_abandon(db, session, delete_sets=True)
        if kind == "approve_proposal":
            return self._apply_resolve_proposal(
                db, session, session["user_id"], payload, origin, command_id, approve=True
            )
        if kind == "reject_proposal":
            return self._apply_resolve_proposal(
                db, session, session["user_id"], payload, origin, command_id, approve=False
            )
        if kind == "healthkit_state":
            return self._apply_healthkit_state(db, session, payload)
        raise ValueError(f"unhandled kind {kind}")

    def _bump(self, db: Session, session_id: str, origin: str) -> None:
        db.execute(text("""
            UPDATE active_workout_session
            SET version = version + 1, updated_at = NOW(),
                last_device_sync_at = NOW(), origin_device = COALESCE(origin_device, :origin)
            WHERE id = :sid
        """), {"sid": session_id, "origin": origin})

    def _record_command(
        self, db: Session, command_id: str, session_id: Optional[str], user_id: str,
        origin: str, kind: str, expected_version: Optional[int],
        payload: Dict[str, Any], result: Dict[str, Any], status: str,
    ) -> None:
        db.execute(text("""
            INSERT INTO workout_session_command (
                command_id, session_id, user_id, origin_device, kind,
                expected_version, payload, result, status, applied_at
            ) VALUES (
                :cid, :sid, :uid, :origin, :kind,
                :ver, CAST(:payload AS jsonb), CAST(:result AS jsonb), :status, NOW()
            )
            ON CONFLICT (command_id) DO NOTHING
        """), {
            "cid": command_id, "sid": session_id, "uid": user_id, "origin": origin,
            "kind": kind, "ver": expected_version,
            "payload": json.dumps(payload, default=str),
            "result": json.dumps(result, default=str),
            "status": status,
        })

    # ────────────────────────────────────────────────────────────────────
    # Mutations — none of these commit; `execute` owns the transaction.
    # ────────────────────────────────────────────────────────────────────

    async def _apply_log_set(
        self, db: Session, session: Dict[str, Any], payload: Dict[str, Any], command_id: str
    ) -> Dict[str, Any]:
        from app.services.workout_session_service import workout_session_service as legacy

        snap = session["workout_snapshot"]
        exercises: List[Dict[str, Any]] = snap.get("exercises") or []
        # The Watch names the exercise it thinks it is on; trusting that over
        # the shared cursor is what stops a phone-side jump mid-set from
        # silently redirecting the Watch's set to another lift.
        ex_idx = payload.get("exercise_index")
        ex_idx = session["current_exercise_index"] if ex_idx is None else int(ex_idx)
        if ex_idx < 0 or ex_idx >= len(exercises):
            raise WorkoutConflict("session_mismatch", "That exercise is no longer in this workout.")

        ex = exercises[ex_idx]
        base_name = ex["name"]
        exercise_name = legacy._effective_name(ex)
        target_sets = ex.get("sets") or 0

        rpe = payload.get("rpe")
        effort = (payload.get("effort") or payload.get("rpe_feeling") or "").strip().lower()
        if rpe is None and effort:
            rpe = EFFORT_RPE.get(effort, 7)

        weight = payload.get("weight")
        if weight is None:
            weight = ex.get("approved_weight") or ex.get("suggested_weight") or 0
        reps = payload.get("reps")
        if reps is None:
            target_reps = str(ex.get("reps", "8"))
            reps = int(target_reps.split("-")[0]) + 1 if "-" in target_reps else int(target_reps)

        counts_before = self._name_counts(db, session["id"])
        set_index = min(counts_before.get(exercise_name, 0), max(target_sets - 1, 0))

        log_id = str(uuid.uuid4())
        variant = (ex.get("variant") or "").strip() or None
        flags = json.dumps({"base_exercise": base_name, "variant": variant}) if variant else None
        db.execute(text("""
            INSERT INTO workout_log (
                id, workout_id, user_id, exercise_id, set_index, weight, reps, rpe, notes,
                session_date, session_time, active_session_id, flags, command_id
            ) VALUES (
                :id, :wid, :uid, :ex, :si, :w, :r, :rpe, :notes,
                :sdate, :stime, :sid, CAST(:flags AS json), :cid
            )
        """), {
            "id": log_id, "wid": session["id"], "uid": session["user_id"],
            "ex": exercise_name, "si": set_index + 1,
            "w": weight, "r": reps, "rpe": rpe, "notes": payload.get("notes"),
            "sdate": date.today(),
            # Real UTC instant — the container runs in ET, so a naive now()
            # would land 4-5h early and break the Watch time-overlap meld.
            "stime": datetime.now(timezone.utc),
            "sid": session["id"], "flags": flags, "cid": command_id,
        })

        # Cursor is derived from what is actually logged, never from an
        # incrementing pointer — that is what supports doing exercises in any
        # order and returning to a skipped machine.
        counts = self._name_counts(db, session["id"])
        done = legacy._completed_for(exercises, counts, ex_idx)
        exercise_complete = done >= (target_sets or 0)

        new_ex_idx, new_set_idx = ex_idx, done
        workout_complete, next_idx = False, None
        if exercise_complete:
            next_idx = legacy._next_incomplete_index(exercises, counts, ex_idx)
            if next_idx is None:
                workout_complete = True
            else:
                new_ex_idx = next_idx
                new_set_idx = legacy._completed_for(exercises, counts, next_idx)

        volume = Decimal(str(weight)) * Decimal(str(reps))
        db.execute(text("""
            UPDATE active_workout_session
            SET current_exercise_index = :ei, current_set_index = :si,
                total_sets_completed = total_sets_completed + 1,
                total_volume = total_volume + :vol
            WHERE id = :sid
        """), {"ei": new_ex_idx, "si": new_set_idx, "vol": volume, "sid": session["id"]})

        # Deterministic, immediately-known facts (§6.7 step 2) — PR and rest
        # length need no LLM, so they ride back on the acknowledgement.
        pr_result = None
        try:
            if weight and reps and float(weight) > 0 and int(reps) > 0:
                from app.routes.fitness import check_and_record_pr
                pr_result = await check_and_record_pr(
                    db=db, user_id=session["user_id"], exercise_name=exercise_name,
                    weight=weight, reps=reps, achieved_at=date.today(), workout_set_id=log_id,
                )
                if pr_result and pr_result.get("is_pr"):
                    db.execute(text("UPDATE workout_log SET is_pr = true WHERE id = :id"), {"id": log_id})
        except Exception as e:
            logger.warning(f"[WorkoutCommand] PR check failed (non-fatal): {e}")

        policy = self.get_policy(db, session["user_id"])
        rest_seconds = 0
        if not workout_complete and policy.get("adaptive_rest_enabled", True):
            lo, hi = (policy.get("rest_range_seconds") or [45, 210])[:2]
            rest_seconds = max(int(lo), min(legacy._smart_rest_seconds(exercise_name, rpe), int(hi)))
            # Server-side auto-start is what lets the Watch show a rest
            # countdown it never asked for. The phone has always driven its own
            # timer locally, so this stays off until the v2 cutover to keep the
            # current phone behaviour bit-identical.
            if _v2_enabled() and policy.get("auto_start_rest_after_set", True):
                db.execute(text("""
                    UPDATE active_workout_session
                    SET rest_timer_started_at = NOW(), rest_timer_duration_seconds = :d
                    WHERE id = :sid
                """), {"d": rest_seconds, "sid": session["id"]})

        # An RPE that overshoots the approved target is a recommendation, not a
        # licence to change the next set (§11.2).
        proposal = None
        if not workout_complete and rpe is not None:
            proposal = self._maybe_propose_weight(
                db, session, exercises, new_ex_idx, rpe, reps, float(weight)
            )

        return {
            "logged": {
                "id": log_id, "exercise": exercise_name, "exercise_index": ex_idx,
                "set_number": set_index + 1, "weight": float(weight), "reps": int(reps), "rpe": rpe,
            },
            "pr": pr_result if (pr_result and pr_result.get("is_pr")) else None,
            "rest_seconds": rest_seconds,
            "exercise_complete": exercise_complete and not workout_complete,
            "workout_complete": workout_complete,
            "next_exercise_index": None if workout_complete else new_ex_idx,
            "proposal": proposal,
        }

