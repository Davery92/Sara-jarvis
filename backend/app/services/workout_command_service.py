    def _apply_set_policy(
        self, db: Session, user_id: str, payload: Dict[str, Any], origin: str
    ) -> Dict[str, Any]:
        """Record a standing bounded approval (§6.9).

        Only keys Sara already knows about are stored — she cannot widen her
        own scope by inventing a policy name.
        """
        current = self.get_policy(db, user_id)
        incoming = payload.get("policy") or payload
        merged = {**current, **{k: v for k, v in incoming.items() if k in DEFAULT_POLICY}}

        rng = merged.get("rest_range_seconds") or DEFAULT_POLICY["rest_range_seconds"]
        try:
            lo, hi = int(rng[0]), int(rng[1])
            merged["rest_range_seconds"] = [max(15, lo), max(max(15, lo), min(hi, 600))]
        except (TypeError, ValueError, IndexError):
            merged["rest_range_seconds"] = DEFAULT_POLICY["rest_range_seconds"]

        db.execute(text("""
            INSERT INTO workout_approved_policy (user_id, policy, approved_by_device, updated_at)
            VALUES (:uid, CAST(:p AS jsonb), :dev, NOW())
            ON CONFLICT (user_id) DO UPDATE
              SET policy = CAST(:p AS jsonb), approved_by_device = :dev,
                  approved_at = NOW(), updated_at = NOW()
        """), {"uid": user_id, "p": json.dumps(merged), "dev": origin})
        return {"status": "accepted", "policy": merged}

    def get_policy(self, db: Session, user_id: str) -> Dict[str, Any]:
        try:
            row = db.execute(text(
                "SELECT policy FROM workout_approved_policy WHERE user_id = :uid"
            ), {"uid": user_id}).fetchone()
        except Exception:
            return dict(DEFAULT_POLICY)
        if not row or not row.policy:
            return dict(DEFAULT_POLICY)
        stored = row.policy if isinstance(row.policy, dict) else json.loads(row.policy)
        return {**DEFAULT_POLICY, **stored}

