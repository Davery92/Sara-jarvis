    def sync(
        self, db: Session, user_id: str, after_version: Optional[int] = None, *, compact: bool = False
    ) -> Dict[str, Any]:
        row = db.execute(text("""
            SELECT id FROM active_workout_session WHERE user_id = :uid AND status = 'active' LIMIT 1
        """), {"uid": user_id}).fetchone()
        if not row:
            return {"projection": None, "events": []}
        session = self._load_by_id(db, row.id)
        return {
            "projection": self.projection(db, session, compact=compact),
            "events": self.list_events(db, row.id, after_version=after_version),
        }

    def catalog(self, db: Session, user_id: str, limit: int = 8) -> Dict[str, Any]:
        """Compact template list the Watch caches so it can start standalone (§7.5).

        Deliberately thin: enough to render a pre-start summary, never enough
        to build a competing workout snapshot — the backend still owns that.
        """
        from app.services.training_day import is_training_day

        rows = db.execute(text("""
            SELECT id, name, exercises, scheduled_days
            FROM fitness_template
            WHERE user_id = :uid
            ORDER BY updated_at DESC NULLS LAST, created_at DESC NULLS LAST
            LIMIT :lim
        """), {"uid": user_id, "lim": limit}).fetchall()

        templates = []
        for r in rows:
            raw = r.exercises or "[]"
            exercises = json.loads(raw) if isinstance(raw, str) else (raw or [])
            templates.append({
                "id": r.id,
                "name": r.name,
                "exercise_count": len(exercises),
                "exercises": [{
                    "name": e.get("name"),
                    "sets": e.get("sets"),
                    "reps": e.get("reps"),
                } for e in exercises[:12]],
            })

        today_template_id = None
        try:
            today = is_training_day(db, user_id, date.today())
            if isinstance(today, dict):
                today_template_id = today.get("template_id")
        except Exception as e:
            logger.debug(f"[WorkoutCommand] training-day lookup failed: {e}")

        active = db.execute(text("""
            SELECT id FROM active_workout_session WHERE user_id = :uid AND status = 'active' LIMIT 1
        """), {"uid": user_id}).fetchone()

        return {
            "schema_version": SCHEMA_VERSION,
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "today_template_id": today_template_id,
            "templates": templates,
            "active_projection": (
                self.projection(db, self._load_by_id(db, active.id), compact=True) if active else None
            ),
            "policy": self.get_policy(db, user_id),
        }

    def link_healthkit(
        self, db: Session, user_id: str, session_id: str, healthkit_workout_uuid: str,
        *, activity_type: Optional[str] = None, started_at: Optional[str] = None,
        ended_at: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Bind the exact HealthKit workout to the Sara session (§6.4).

        Idempotent, and safe to call before the matching `external_workout` row
        has been ingested — the UUID is stored on the session either way, and
        ingestion picks the link up from there.
        """
        row = db.execute(text("""
            SELECT id FROM active_workout_session WHERE id = :sid AND user_id = :uid
        """), {"sid": session_id, "uid": user_id}).fetchone()
        if not row:
            raise ValueError("Session not found")

        db.execute(text("""
            UPDATE active_workout_session
            SET healthkit_workout_uuid = :hk,
                healthkit_activity_type = COALESCE(:act, healthkit_activity_type),
                healthkit_started_at = COALESCE(CAST(:st AS timestamptz), healthkit_started_at),
                healthkit_ended_at = COALESCE(CAST(:en AS timestamptz), healthkit_ended_at),
                healthkit_state = 'ended', last_device_sync_at = NOW(), updated_at = NOW()
            WHERE id = :sid
        """), {"hk": healthkit_workout_uuid, "act": activity_type,
               "st": started_at, "en": ended_at, "sid": session_id})

        linked = db.execute(text("""
            UPDATE external_workout SET sara_session_id = :sid
            WHERE user_id = :uid AND external_id = :hk AND sara_session_id IS DISTINCT FROM :sid
            RETURNING id
        """), {"sid": session_id, "uid": user_id, "hk": healthkit_workout_uuid}).fetchone()
        db.commit()
        return {"success": True, "session_id": session_id,
                "healthkit_workout_uuid": healthkit_workout_uuid,
                "external_workout_linked": bool(linked)}

    def _linked_heart_rate(
        self, db: Session, session: Dict[str, Any], hk_uuid: Optional[str]
    ) -> Optional[Dict[str, Any]]:
        """Physiology for this exact workout, by explicit link only.

        Returns None rather than guessing — the caller falls back to the legacy
        same-day heuristic, which stays until real-device parity (§16.2).
        """
        uuid_ = hk_uuid or session.get("healthkit_workout_uuid")
        if not uuid_:
            return None
        row = db.execute(text("""
            SELECT activity_type, avg_heart_rate, max_heart_rate, min_heart_rate,
                   total_energy_kcal, total_distance_m, duration_seconds
            FROM external_workout
            WHERE user_id = :uid AND external_id = :hk LIMIT 1
        """), {"uid": session["user_id"], "hk": uuid_}).fetchone()
        if not row:
            return None
        from app.services.workout_session_service import workout_session_service as legacy
        return {
            "activity": legacy._ACTIVITY_NAMES.get(str(row.activity_type), "Workout"),
            "avg_heart_rate": row.avg_heart_rate,
            "max_heart_rate": row.max_heart_rate,
            "min_heart_rate": row.min_heart_rate,
            "calories": round(float(row.total_energy_kcal)) if row.total_energy_kcal is not None else None,
            "distance_m": round(float(row.total_distance_m)) if row.total_distance_m is not None else None,
            "duration_min": round(row.duration_seconds / 60) if row.duration_seconds else None,
            "linked": True,
        }


