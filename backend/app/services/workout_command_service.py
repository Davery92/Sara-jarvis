"""Versioned, idempotent workout command service.

SARA_APPLE_WATCH_FITNESS_IMPLEMENTATION_PLAN_2026_07_25 §5, §6.2, §6.5-§6.8.

Why this exists: `workout_session_service` was written when the phone was the
only controller, so each mutation was "read state, write state, commit". With
the Watch as a second controller that stops being safe — a retried Log Set over
a flaky link writes a second set, and two devices can interleave writes on the
same row.

Every mutation now goes through `execute()`, which is the ONLY place workout
state changes. It follows the sequence in §6.2 exactly:

    begin -> replay if command_id seen -> lock the session row -> validate
    user/session/status/version -> apply once -> bump version -> store the
    result projection -> commit

`command_id` is generated by the client *before* sending, so a command whose
response was lost can be retried byte-identically and will replay the original
result instead of applying twice.

Coaching is deliberately NOT part of this path (§6.7). A set is durable and
acknowledged the moment it commits; the LLM sentence arrives later as a
`workout_session_event` row. A dead LLM can no longer make `Log Set` feel
broken.

The legacy `/workout-session/*` endpoints call in here too, via the adapters in
`workout_session_service`, so there is exactly one mutation implementation
(§6.5) rather than a phone path and a Watch path that drift apart.
"""

