    """The Friday 06:23 deliberation invented "David is a WFH day" from a
    No-School calendar event with nothing to contradict it, and every
    render site downstream (life_facts, world_brief's BODY & TRAINING,
    the journal reading its own wrong guess back) repeated it verbatim all
    weekend. One away_mode() gate, applied at each render site."""

