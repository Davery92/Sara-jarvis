"""
Regression fixture for the Sep 3-7 2026 Salem-trip "amnesia" bug
(docs/SARA_AMNESIA_FIX_PLAN_2026_09_06.md).

fixtures/amnesia_2026_09_04_turn0.txt is the actual assembled prompt Sara
received Friday 2026-09-04 07:25 ET (conversation_turn id
7f5e17d8-a544-4d0a-b8af-d6ea039c8969, message_index=0, conversation
b8f9736f-8f19-48ff-b28b-1261e116ffe8) — captured once, read-only, never
regenerated by any test. It demonstrates every symptom below actually
happened in production; it is a reference, not something re-rendered here.

Each `TestPhaseN...` class instead exercises the real rendering functions
with inputs shaped like that morning's, so the assertion is red before its
phase lands and green after — a live check, not a frozen transcript diff.
"""
from pathlib import Path

FIXTURE_PATH = Path(__file__).parent / "fixtures" / "amnesia_2026_09_04_turn0.txt"


def test_fixture_demonstrates_the_original_bug():
    """If this ever fails, the fixture file was edited — it shouldn't be;
    it's the frozen evidence the rest of this suite guards against recurring."""
    text = FIXTURE_PATH.read_text()
    brief_block = text.split("## Today's Brief")[1].split("## Knowledge Graph")[0]
    assert "He has a kitten named Vesper." in brief_block
    assert "in Salem" not in brief_block  # the actual bug: clipped before context.md
    assert "David just returned after 14.9 hours away." in text
    assert text.count("Resting HR") >= 10  # HEALTH DELTAS spam
    assert "location: unknown" in text
    assert "You're working from home today" in text
    assert "leaves for work 7am" in text


