class TestPhase2AwayFromHome:
    """location_service now matches 'suggested' places and writes
    distance_from_home_km/away_since — the fields device_presence and
    deliberation need to stop saying "unknown" for a place David visited
    23 times over a week (gotcha_chat_amnesia_brief_clip_2026_09_06)."""

    def test_describe_location_none_when_not_away(self):
        from app.services.unified_context import describe_location, UnifiedContextSnapshot
        snap = UnifiedContextSnapshot(current_place="Home", distance_from_home_km=0.1)
        assert describe_location(snap) is None

    def test_describe_location_renders_distance_and_place(self):
        from app.services.unified_context import describe_location, UnifiedContextSnapshot
        snap = UnifiedContextSnapshot(
            current_place="near 2 Preston Beach Road, Marblehead (unconfirmed)",
            distance_from_home_km=421.3,
            away_since="2026-09-03T20:31:00+00:00",
        )
        text = describe_location(snap)
        assert "421 km from home" in text
        assert "Marblehead" in text

    def test_device_presence_location_line_replaces_unknown(self):
        from app.services.device_presence import format_context_line, DevicePresence
        presence = DevicePresence(
            active_device_id=None, active_device_name="iPhone", platform="ios",
            activity_level="high", location_context="away", confidence=0.75, since="now",
            location_detail="421 km from home since Thu Sep 3 20:31 (near 2 Preston Beach Road, Marblehead (unconfirmed)).",
        )
        text = format_context_line(presence)
        assert "location: unknown" not in text
        assert "421 km from home" in text

    def test_away_mode_true_from_distance_and_duration(self):
        from datetime import datetime, timedelta, timezone
        from app.services.unified_context import away_mode, UnifiedContextSnapshot
        snap = UnifiedContextSnapshot(
            distance_from_home_km=421.0,
            away_since=(datetime.now(timezone.utc) - timedelta(hours=8)).isoformat(),
        )
        assert away_mode(snap) is True

    def test_away_mode_false_when_recently_away(self):
        from datetime import datetime, timedelta, timezone
        from app.services.unified_context import away_mode, UnifiedContextSnapshot
        snap = UnifiedContextSnapshot(
            distance_from_home_km=421.0,
            away_since=(datetime.now(timezone.utc) - timedelta(hours=1)).isoformat(),
        )
        assert away_mode(snap) is False

    def test_away_mode_true_from_verified_upcoming_trip_line(self):
        from app.services.unified_context import away_mode, UnifiedContextSnapshot
        snap = UnifiedContextSnapshot()
        upcoming = ["Thu Sep 3 (all day)–Mon Sep 7 (all day): Salem"]
        # Only meaningful "today" in the real trip window; here we just check
        # the parser recognizes the date-range shape without raising.
        assert away_mode(snap, verified_upcoming=upcoming) in (True, False)


